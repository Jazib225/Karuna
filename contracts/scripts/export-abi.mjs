// After `forge build`: write the ABI and creation bytecode as TypeScript so the Gatekeeper and
// console use exactly what was compiled. Output is committed (the out/ dir is not).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const art = JSON.parse(readFileSync(resolve(here, "../out/Dharma.sol/Dharma.json"), "utf8"));
const banner = "// GENERATED by contracts/scripts/export-abi.mjs from out/Dharma.sol/Dharma.json — do not edit.\n";
writeFileSync(resolve(here, "../js/abi.ts"), `${banner}export const DHARMA_ABI = ${JSON.stringify(art.abi, null, 2)} as const;\n`);
writeFileSync(resolve(here, "../js/bytecode.ts"), `${banner}export const DHARMA_BYTECODE = "${art.bytecode.object}" as const;\n`);
console.log(`exported ABI (${art.abi.length} entries) and bytecode (${(art.bytecode.object.length - 2) / 2} bytes)`);
