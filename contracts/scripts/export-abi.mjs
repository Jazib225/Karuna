// After `forge build`: write the ABIs and creation bytecode as TypeScript so the Gatekeeper and
// console use exactly what was compiled. Output is committed (the out/ dir is not).
//
// An org's Dharma is two contracts: the Dharma code (deployed once per version) and a DharmaProxy
// that holds the org's address and state and runs that code. The org talks to the proxy with the
// Dharma ABI.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => JSON.parse(readFileSync(resolve(here, `../out/${name}.sol/${name}.json`), "utf8"));
const dharma = read("Dharma");
const proxy = read("DharmaProxy");
const banner = "// GENERATED by contracts/scripts/export-abi.mjs from out/ — do not edit.\n";
writeFileSync(
  resolve(here, "../js/abi.ts"),
  `${banner}export const DHARMA_ABI = ${JSON.stringify(dharma.abi, null, 2)} as const;\n\nexport const DHARMA_PROXY_ABI = ${JSON.stringify(proxy.abi, null, 2)} as const;\n`,
);
writeFileSync(
  resolve(here, "../js/bytecode.ts"),
  `${banner}export const DHARMA_BYTECODE = "${dharma.bytecode.object}" as const;\nexport const DHARMA_PROXY_BYTECODE = "${proxy.bytecode.object}" as const;\n`,
);
const size = (o) => (o.bytecode.object.length - 2) / 2;
console.log(`exported Dharma (${dharma.abi.length} ABI entries, ${size(dharma)} bytes) and DharmaProxy (${size(proxy)} bytes)`);
