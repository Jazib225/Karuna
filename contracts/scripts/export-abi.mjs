// After `forge build`: write the ABIs and creation bytecode as TypeScript so the Gatekeeper and
// console use exactly what was compiled. Output is committed (the out/ dir is not).
//
// An org's Dharma is a DharmaProxy (the org's address and all its state) running code deployed once
// per version. Since v6 that code is two contracts: Dharma (proposals, votes, execution) and DharmaExt
// (setup, roles, reports, views), which Dharma forwards to. The org is called with DHARMA_ABI, both
// halves as one (from DharmaAbi.sol). Escrow is a separate, per-org contract for held payments.
//
// Also the size gate: this fails if a contract gets within 1 KB of the 24,576-byte limit.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => JSON.parse(readFileSync(resolve(here, `../out/${name}.sol/${name}.json`), "utf8"));
const dharma = read("Dharma");
const ext = read("DharmaExt");
const abi = read("DharmaAbi");
const proxy = read("DharmaProxy");
const escrow = read("Escrow");
const banner = "// GENERATED by contracts/scripts/export-abi.mjs from out/ — do not edit.\n";
writeFileSync(
  resolve(here, "../js/abi.ts"),
  `${banner}export const DHARMA_ABI = ${JSON.stringify(abi.abi, null, 2)} as const;\n\nexport const DHARMA_PROXY_ABI = ${JSON.stringify(proxy.abi, null, 2)} as const;\n\nexport const ESCROW_ABI = ${JSON.stringify(escrow.abi, null, 2)} as const;\n`,
);
writeFileSync(
  resolve(here, "../js/bytecode.ts"),
  `${banner}/** Dharma's creation code; its constructor takes the DharmaExt address (deploy that first). */\nexport const DHARMA_BYTECODE = "${dharma.bytecode.object}" as const;\nexport const DHARMA_EXT_BYTECODE = "${ext.bytecode.object}" as const;\nexport const DHARMA_PROXY_BYTECODE = "${proxy.bytecode.object}" as const;\nexport const ESCROW_BYTECODE = "${escrow.bytecode.object}" as const;\n`,
);
const size = (o) => (o.deployedBytecode.object.length - 2) / 2; // runtime code: what EIP-170 limits
console.log(
  `exported Dharma (${size(dharma)} bytes) + DharmaExt (${size(ext)} bytes) as one ABI (${abi.abi.length} entries), DharmaProxy (${size(proxy)} bytes) and Escrow (${escrow.abi.length} ABI entries, ${size(escrow)} bytes)`,
);
const LIMIT = 24_576;
const MARGIN = 1024;
const tight = [["Dharma", dharma], ["DharmaExt", ext], ["Escrow", escrow]].filter(([, o]) => size(o) > LIMIT - MARGIN);
if (tight.length) {
  for (const [n, o] of tight) console.error(`${n} is ${size(o)} bytes, within ${MARGIN} bytes of the ${LIMIT}-byte contract limit. Move code out of it before adding more.`);
  process.exit(1);
}
